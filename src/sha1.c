	sha1_init(&ctx_2);
	sha1_update(&ctx_2, test_2, sizeof(test_2));
	sha1_final(&ctx_2, digest_2);

	assert(memcmp(expected_2, digest_2, 20) == 0);

	/* test 3, 1M 'a' */
	Sha1Ctx ctx_3;

static TestResult sha1_test_abc(void)
{
	Sha1Ctx *ctx;
	u8 digest[20];
	char test[3] = "abc";
	u8 expected[20] = { 0xA9, 0x99, 0x3E, 0x36, 0x47, 0x06, 0x81, 0x6A, 0xBA, 0x3E, 0x25, 0x71, 0x78, 0x50, 0xC2, 0x6C, 0x9C, 0xD0, 0xD8, 0x9D };

    ctx = sha1_new();
	sha1_init(ctx);
	sha1_update(ctx, test, sizeof(test));
	sha1_final(ctx, digest);

    sha1_destroy(ctx);

    return (memcmp(expected, digest, 20) == 0) ? PASS : FAIL;
}



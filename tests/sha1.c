static TestResult sha1_test_1mill_a(void)
{
	Sha1Ctx *ctx;
    int i;
	u8 digest[20];
	char test[1000000];

	i = 0;
	memset(test, 0x61, 1000000);
	u8 expected[20] = { 0x34, 0xAA, 0x97, 0x3C, 0xD4, 0xC4, 0xDA, 0xA4, 0xF6, 0x1E, 0xEB, 0x2B, 0xDB, 0xAD, 0x27, 0x31, 0x65, 0x34, 0x01, 0x6F };

    ctx = sha1_new();
	sha1_init(ctx);
	while(i < 1000000)
	{
		sha1_update(ctx, &test[i], 1000);
		i += 1000;
	}
	sha1_final(ctx, digest);

    sha1_destroy(ctx);

    return ((memcmp(expected, digest, 20)) == 0) ? PASS : FAIL;
}

static TestResult sha1_test_monte_carlo_sim(void)
{
    Sha1Ctx *ctx;
    int a, b;
    unsigned char seed[20] = SHA1_MONTE_CARLO_SEED;
    unsigned char state[4][20];
    unsigned char m[60];

    for(a = 0; a < 100; a++)
    {
        memcpy(state[0], seed, 20);
        memcpy(state[1], seed, 20);
        memcpy(state[2], seed, 20);
        memcpy(state[3], seed, 20);
        for(b = 0; b < 1000; b++)
        {
            ctx = sha1_new();
            sha1_init(ctx);
            memcpy(m, state[(b+1)&3], 20);
            memcpy(m+20, state[(b+2)&3], 20);
            memcpy(m+40, state[(b+3)&3], 20);
            sha1_update(ctx, m, 60);
            sha1_final(ctx, state[b&3]);
            memcpy(seed, state[b&3], 20);
            sha1_destroy(ctx);
        }
        if ((memcmp(sha1_monte_carlo_expected[a], seed, 20)) != 0)
            return FAIL;
    }

    return PASS;
}

